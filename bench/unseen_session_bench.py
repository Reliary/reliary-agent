def load_queries(probes_path=None):
    """Load probes from file. probes_path can be absolute or relative to bench/."""
    if probes_path is None:
        probes_path = HERE / "results" / "reliary8_probes.json"
    p = Path(probes_path)
    if not p.is_absolute():
        p = HERE / p
    with open(p) as f:
        return json.load(f)

def build_focused_pack(queries, project):
    """Build a holographic pack containing ONLY the symbols referenced in queries.
    This keeps the pack small (10-20 symbols instead of 481)."""
    # Extract function names from probes
    funcs = set()
    for q in queries:
        rubric = q.get("rubric", {})
        fn = rubric.get("function")
        if fn:
            funcs.add(fn)
    # Always include the well-known ones even if not in rubric
    funcs.update({"skeleton", "aggressive_skeleton", "skeleton_hash", "classify_line",
                  "should_drop", "detect_strategy", "compress_content", "score"})
    funcs = sorted(funcs)
    # Run the pack generator, then filter
    out = subprocess.run(
        [mth.RELIARY_BIN, "pack", project],
        capture_output=True, text=True, timeout=30,
        cwd=project
    )
    if out.returncode != 0:
        print(f"pack failed: {out.stderr[:300]}")
        return None
    full_pack = out.stdout
    # Filter: keep header + only entries whose ## name is in funcs
    lines = full_pack.split("\n")
    header = []
    body = []
    in_body = False
    current_entry = []
    current_name = None
    for line in lines:
        if line.startswith("## "):
            if current_entry and current_name in funcs:
                body.extend(current_entry)
            current_name = line[3:].split("/")[0].strip()
            current_entry = [line]
        elif line:
            current_entry.append(line)
        else:
            current_entry.append(line)
    if current_entry and current_name in funcs:
        body.extend(current_entry)
    focused = "\n".join(header) + "\n" + "\n".join(body)
    print(f"focused pack: {len(focused)} chars, {len(body)} lines, {len([l for l in body if l.startswith('## ')])} symbols")
    return focused


def build_auto_pack(project):
    """Build a holographic pack using --auto (gate + hotspot selection).
    This is the production mode — no probe-knowledge needed."""
    out = subprocess.run(
        [mth.RELIARY_BIN, "pack", "--auto", project],
        capture_output=True, text=True, timeout=60,
        cwd=project
    )
    if out.returncode != 0:
        print(f"auto pack failed: {out.stderr[:300]}")
        return None
    pack = out.stdout
    # Count symbols
    n_symbols = sum(1 for l in pack.split("\n") if l.startswith("## "))
    print(f"auto pack: {len(pack)} chars, {n_symbols} symbols (gate + hotspot)")
    return pack if pack else None


def build_full_pack(project):
    """Build the FULL pack (all symbols) for query-time slicing.
    This is pre-built once; sliced per-query in condition F."""
    out = subprocess.run(
        [mth.RELIARY_BIN, "pack", project],
        capture_output=True, text=True, timeout=300,
        cwd=project
    )
    if out.returncode != 0:
        print(f"full pack failed: {out.stderr[:300]}")
        return None
    pack = out.stdout
    n_symbols = sum(1 for l in pack.split("\n") if l.startswith("## "))
    print(f"full pack: {len(pack)} chars, {n_symbols} symbols (for slicing)")
    return pack


def _extract_func_names_from_question(question):
    """Extract function names (with underscores) from a question string.
    
    Looks for identifiers matching [a-z][a-z0-9_]* that look like function
    names (contain underscores, not all caps, length > 3).
    """
    import re
    candidates = re.findall(r'\b[a-z][a-z0-9_]{3,}\b', question)
    # Prefer names with underscores (more likely function names)
    func_like = [c for c in candidates if "_" in c and len(c) > 5]
    if func_like:
        return func_like
    return candidates[:3]


def slice_pack_for_query(full_pack, query, top_k=10):
    """Slice the full pack for a specific query using the Python BM25 fallback.
    
    Always uses Python BM25 (the CLI slicer requires a project path and can't
    operate on an in-memory pack string).
    """
    return _slice_pack_python(full_pack, query, top_k)


def _slice_pack_python(full_pack, query, top_k):
    """Python fallback slicer — BM25 over pack entries."""
    import math
    from collections import Counter

    # Parse entries
    entries = []
    current_name = None
    current_header = ""
    current_body = ""
    for line in full_pack.split("\n"):
        if line.startswith("## "):
            if current_name:
                entries.append((current_name, current_header, current_body))
            current_name = line[3:].split("/")[0].strip()
            current_header = line
            current_body = ""
        elif current_name:
            current_body += line + "\n"
    if current_name:
        entries.append((current_name, current_header, current_body))

    if not entries:
        return ""

    # Tokenize
    def tokenize(text):
        return [w.lower() for w in text.split() if len(w) > 1]

    query_tokens = set(tokenize(query))
    if not query_tokens:
        return "\n".join(f"{h}\n{b}" for _, h, b in entries[:top_k])

    # BM25 scoring with substring fallback for abbreviation matching.
    # E.g., "findcl" should match "find_clusters" via prefix overlap.
    n_docs = len(entries)
    doc_tokens = [tokenize(f"{name} {body}") for name, _, body in entries]
    avgdl = sum(len(d) for d in doc_tokens) / max(n_docs, 1)

    # Document frequencies
    df = Counter()
    for dt in doc_tokens:
        for t in set(dt):
            for qt in query_tokens:
                if qt in t or t in qt:
                    df[t] += 1
                    break

    scored = []
    for i, (name, header, body) in enumerate(entries):
        dl = len(doc_tokens[i])
        tf = Counter(doc_tokens[i])
        score = 0.0
        for qt in query_tokens:
            d_freq = df.get(qt, 0)
            if d_freq == 0:
                continue
            idf = math.log((n_docs - d_freq + 0.5) / (d_freq + 0.5) + 1.0)
            term_freq = tf.get(qt, 0)
            if term_freq > 0:
                bm25 = idf * (term_freq * 2.2) / (term_freq + 1.2 * (1 - 0.75 + 0.75 * dl / max(avgdl, 1)))
                score += bm25
        # Name boost (includes substring/abbreviation matching)
        name_lower = name.lower()
        for qt in query_tokens:
            if name_lower == qt:
                score += 5.0
            elif qt in name_lower:
                score += 2.0
            elif name_lower.startswith(qt) or name_lower.split("_")[0].startswith(qt[:5]):
                # Handle abbreviations like "findcl" -> "find_clusters"
                score += 1.5
        scored.append((score, header, body))

    scored.sort(key=lambda x: -x[0])
    selected = [(h, b) for s, h, b in scored[:top_k] if s > 0]

    if not selected:
        return ""
    return "\n\n".join(f"{h}\n{b}" for h, b in selected)

