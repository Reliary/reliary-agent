def classify_query_needs_slice(query_text: str) -> bool:
    """Return True if the query benefits from the sliced pack, False if model likely knows it.
    
    Based on N→F analysis:
    - N=3 queries: model knows from training, slice wastes tokens
    - N=0 F≥2 queries: slice is essential
    - bug_* queries: slice provides L3 surprise (N→F Δ = +1.8)
    - _crossref queries: slice provides caller lists (N→F Δ = +1.0)
    - _detail queries: slice provides specific values (N→F Δ = +1.4)
    - arch_* queries: model already knows (N=3 F=3, Δ=0) — skip
    - _discriminate queries: marginal gain (Δ=+0.2) — skip to save cost
    - _edge queries: marginal gain (Δ=+0.5) — skip
    - _what queries: moderate gain (Δ=+0.8) — skip
    """
    text = query_text.lower()
    # Always slice: bug detection and cross-references (biggest deltas)
    if "bug" in text or "issue" in text or "wrong" in text or "incorrect" in text or "missing" in text:
        return True
    if "call" in text or "caller" in text or "who uses" in text or "references" in text or "called by" in text:
        return True
    # Always slice: detail questions need specific values
    if "value" in text or "threshold" in text or "parameter" in text or "default" in text or "exactly" in text or "what number" in text:
        return True
    # Always slice: question mentions specific symbol names that might not be in training
    func_indicators = ["find_clusters", "skelhash", "skeleton_hash", "aggressive_skeleton", 
                       "maxwell", "should_drop", "detect_strategy", "callgraph", "is_definition_line"]
    if any(f in text for f in func_indicators):
        return True
    # Skip slice: architecture, discriminate, edge, what questions (model already knows or marginal gain)
    return False

# Global: full pack for condition F/G slicing (pre-built once)
FULL_PACK_FOR_SLICING = None

def run_session(cond, queries, model, seed, project, timeout_total=1800):
    """Run a single session with the given queries."""
    rng_idx = seed  # for any randomness in tasks
    sys_prompt = mth.SYSTEM_PROMPTS[cond]
    mth._sessions.clear()
    if cond in ("A", "D", "F", "G", "H", "M1", "M2", "M3", "A2"):
        mth._sessions["reliary"] = mth.MCPSession(mth.RELIARY_BIN, project, "reliary")
    if cond == "E":
        mth._sessions["altbackend"] = mth.MCPSession(mth.ALTBACKEND_BIN, project, "altbackend")
    messages = [{"role": "system", "content": sys_prompt}]
    
    # E2: Tool result cache — avoids repeating the same tool call across queries
    tool_cache = {}  # (tool_name, sorted_args_json) -> output string
    tool_cache_hits = 0
    
    # E3: Search interceptor — pre-check if the search term exists in the pack
    # Build a set of all symbol names from the full pack for fast lookup
    full_pack_symbol_names = set()
    if FULL_PACK_FOR_SLICING:
        for line in FULL_PACK_FOR_SLICING.split("\n"):
            if line.startswith("## "):
                name = line[3:].split("/")[0].strip()
                if name:
                    full_pack_symbol_names.add(name.lower())
    
    metrics = {
        "cond": cond, "cond_name": mth.CONDITION_NAMES.get(cond, cond),
        "model": model, "seed": seed, "queries": [],
        "total_wall_time": 0, "total_tool_calls": 0, "total_turns": 0,
        "total_tokens_in": 0, "total_tokens_out": 0,
        "total_weighted_cost": 0, "total_tool_bytes": 0,
        "total_dead_end_calls": 0, "total_score": 0,
        "total_cached_tokens": 0,
        "tool_cache_hits": 0,
    }
    t_start = time.time()
    for qi, query in enumerate(queries):
        if time.time() - t_start > timeout_total:
            break
        # FIX: Reset messages per query to avoid accumulating conversation history.
        # The original Python experiments were single-shot per query; the accumulated
        # messages inflated cost 8x (3K/query → 49K/query by query 63).
        messages = [{"role": "system", "content": sys_prompt}]
        # For conditions F and G: slice the full pack for this query and prepend
        if cond in ("F", "G", "M1") and FULL_PACK_FOR_SLICING:
            # Extract function names from the question text (handles abbreviations
            # like "findcl" -> "find_clusters" by parsing the question itself).
            func_names = _extract_func_names_from_question(query["question"])
            # Try the first function name found in the question
            query_text = func_names[0] if func_names else query["question"]
            sliced = slice_pack_for_query(FULL_PACK_FOR_SLICING, query_text, 10)
            if sliced:
                user_content = f"## Relevant codebase context (sliced for this query)\n\n{sliced}\n\n---\n\nQuestion: {query['question']}"
            else:
                user_content = query["question"]
        elif cond == "A2" and FULL_PACK_FOR_SLICING and classify_query_needs_slice(query["question"]):
            # Adaptive: only slice when the classifier says it's worth it
            func_names = _extract_func_names_from_question(query["question"])
            query_text = func_names[0] if func_names else query["question"]
            sliced = slice_pack_for_query(FULL_PACK_FOR_SLICING, query_text, 10)
            if sliced:
                user_content = f"## Relevant codebase context (sliced for this query)\n\n{sliced}\n\n---\n\nQuestion: {query['question']}"
            else:
                user_content = query["question"]
        else:
            user_content = query["question"]
        messages.append({"role": "user", "content": user_content})
        q_m = {"query_id": query["id"], "tool_calls": 0, "turns": 0,
               "tokens_in": 0, "tokens_out": 0, "weighted_cost": 0,
               "tool_bytes": 0, "dead_end_calls": 0, "score": 0, "answer": "",
               "tool_names": []}
        for turn in range(MAX_TURNS_PER_QUERY):
            if time.time() - t_start > timeout_total:
                q_m["answer"] = "(session timeout)"
                break
            if turn == MAX_TURNS_PER_QUERY - 1:
                messages.append({"role": "user",
                    "content": "Give your FINAL answer now. ONE LINE: {\"final\": true, \"answer\": \"...\"}"})
            resp = deepseek_chat(messages, model=model, max_tokens=1500,
                                 timeout=60, disable_thinking=True)
            if "error" in resp:
                q_m["answer"] = f"(error: {str(resp['error'])[:200]})"
                break
            msg = resp.get("choices", [{}])[0].get("message", {})
            content = msg.get("content", "") or msg.get("reasoning_content", "")
            usage = resp.get("usage", {})
            q_m["tokens_in"] += usage.get("prompt_tokens", 0)
            q_m["tokens_out"] += usage.get("completion_tokens", 0)
            cached = usage.get("prompt_cache_hit_tokens", 0) or usage.get("cached_tokens", 0)
            metrics["total_cached_tokens"] += cached
            q_m["turns"] = turn + 1
            action_type, action = mth.parse_llm_response(content)
            if action_type == "final":
                q_m["answer"] = action.get("answer", content[:2000])
                q_m["weighted_cost"] = q_m["tokens_in"] + 4 * q_m["tokens_out"]
                break
            elif action_type == "tool":
                tool_name = action.get("tool", action.get("name", ""))
                tool_args = action.get("args", action.get("arguments", action))
                if isinstance(tool_args, str):
                    try:
                        tool_args = json.loads(tool_args) if tool_args.strip().startswith("{") else {"query": tool_args}
                    except Exception:
                        tool_args = {"query": tool_args}
                
                # E2: Tool result cache — only for pack conditions (F, G, D)
                # and only cache successful results (not dead-ends)
                cache_key = (tool_name, json.dumps(tool_args, sort_keys=True))
                if cond in ("F", "G", "D", "M1", "M2", "M3", "A2") and cache_key in tool_cache:
                    output = tool_cache[cache_key]
                    tool_cache_hits += 1
                    q_m["tool_names"].append(f"{tool_name}(cached)")
                    q_m["tool_bytes"] += len(output.encode())
                # E3: Search interceptor — only for pack conditions (F, G, D)
                # and only if the symbol is genuinely not in the pack
                elif cond in ("F", "G", "D", "M1", "M2", "M3", "A2") and "search" in tool_name and full_pack_symbol_names:
                    search_term = (tool_args.get("query") or tool_args.get("q") or 
                                  tool_args.get("pattern") or tool_args.get("name") or "").strip()
                    if search_term:
                        sl = search_term.lower()
                        # Check if the search term or any part of it is in the pack
                        found_exact = sl in full_pack_symbol_names
                        found_partial = any(sl in name or name in sl for name in full_pack_symbol_names)
                        if not found_exact and not found_partial:
                            output = f"(no search results: symbol '{search_term}' not found in codebase index)"
                            tool_cache[cache_key] = output
                            q_m["tool_calls"] += 1
                            q_m["tool_names"].append(tool_name)
                            q_m["tool_bytes"] += len(output.encode())
                            # This is a CORRECT dead-end (symbol doesn't exist), don't count as bad
                            messages.append({"role": "assistant", "content": content})
                            messages.append({"role": "user", "content": f"Tool result:\n{output[:8000]}"})
                            continue
                    # Symbol might exist — make the real call
                    output, _ = mth.execute_tool(cond, tool_name, tool_args)
                    is_dead = any(output.strip().startswith(m) for m in ["(no ", "(no results)", "(no definition", "(no trace", "(no search", "(error", "(altbackend error", "(grep error", "(read error"])
                    if not is_dead:
                        tool_cache[cache_key] = output
                    q_m["tool_calls"] += 1
                    q_m["tool_names"].append(tool_name)
                    q_m["tool_bytes"] += len(output.encode())
                    if is_dead:
                        q_m["dead_end_calls"] += 1
                else:
                    output, _ = mth.execute_tool(cond, tool_name, tool_args)
                    # E2: Only cache NON-dead-end results (dead-ends are not useful to reuse)
                    is_dead = any(output.strip().startswith(m) for m in ["(no ", "(no results)", "(no definition", "(no trace", "(no search", "(error", "(altbackend error", "(grep error", "(read error"])
                    if not is_dead:
                        tool_cache[cache_key] = output
                    q_m["tool_calls"] += 1
                    q_m["tool_names"].append(tool_name)
                    q_m["tool_bytes"] += len(output.encode())
                    if is_dead:
                        q_m["dead_end_calls"] += 1
                messages.append({"role": "assistant", "content": content})
                messages.append({"role": "user", "content": f"Tool result:\n{output[:8000]}"})
            else:
                q_m["answer"] = content[:2000]
                q_m["weighted_cost"] = q_m["tokens_in"] + 4 * q_m["tokens_out"]
                break
        q_m["score"] = mth.score_answer(query, q_m["answer"])
        if q_m["answer"] and not q_m["answer"].startswith("("):
            messages.append({"role": "assistant", "content": q_m["answer"]})
        for k in ["tokens_in", "tokens_out", "tool_calls", "turns",
                  "weighted_cost", "tool_bytes", "dead_end_calls", "score"]:
            metrics[f"total_{k}"] += q_m[k]
        metrics["queries"].append(q_m)
    metrics["total_wall_time"] = time.time() - t_start
    metrics["tool_cache_hits"] = tool_cache_hits
    mth._close_sessions()
    return metrics

